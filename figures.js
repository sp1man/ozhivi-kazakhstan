// SVG одной фигуры: mode 'outline' — белые части для печати, 'color' — раскрашенный пример.
window.figureSVG = function (fig, mode, stroke) {
  const w = stroke || 6;
  const paths = fig.parts.map(p => {
    const fill = p.fill === 'none' ? 'none' : (mode === 'color' ? p.fill : '#fff');
    return `<path d="${p.d}" fill="${fill}" stroke="#111" stroke-width="${w}" stroke-linejoin="round" stroke-linecap="round"/>`;
  }).join('');
  return `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 400 400">${paths}</svg>`;
};
